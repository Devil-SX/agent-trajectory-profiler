_SECTION_STATUS = Literal["completed", "failed"]


def _extract_text_fragments(message: MessageRecord) -> list[str]:
    parts: list[str] = []
    if message.summary:
        parts.append(message.summary)
    if message.message is None:
        return parts
    content = message.message.content
    if isinstance(content, str):
        parts.append(content)
        return parts
    if not isinstance(content, list):
        return parts
    for block in content:
        if not isinstance(block, dict):
            continue
        block_type = block.get("type")
        if block_type == "text" and isinstance(block.get("text"), str):
            parts.append(str(block["text"]))
        elif block_type == "thinking" and isinstance(block.get("thinking"), str):
            parts.append(str(block["thinking"]))
        elif block_type == "tool_use" and isinstance(block.get("name"), str):
            parts.append(f"tool:{block['name']}")
        elif block_type == "tool_result":
            block_content = block.get("content")
            if isinstance(block_content, str):
                parts.append(block_content)
    return parts


def _message_char_count(message: MessageRecord) -> int:
    return sum(len(fragment) for fragment in _extract_text_fragments(message))


def _message_tool_call_count(message: MessageRecord) -> int:
    if message.message is None or not isinstance(message.message.content, list):
        return 0
    count = 0
    for block in message.message.content:
        if isinstance(block, dict) and block.get("type") == "tool_use":
            count += 1
    return count


def _message_usage(message: MessageRecord) -> tuple[int, int]:
    usage = message.message.usage if message.message is not None else None
    if usage is None:
        return 0, 0
    return int(usage.input_tokens or 0), int(usage.output_tokens or 0)


def _clip_list(values: list[str], *, limit: int) -> list[str]:
    seen: list[str] = []
    for value in values:
        normalized = _normalize_whitespace(value)
        if not normalized or normalized in seen:
            continue
        seen.append(normalized)
        if len(seen) >= limit:
            break
    return seen


def _default_section_title(messages: list[MessageRecord], section_index: int) -> str:
    for message in messages:
        if message.is_user_message:
            text = " ".join(_extract_text_fragments(message))
            title = _truncate_text(text or f"Section {section_index}", 72)
            if title:
                return title
    if section_index == 0:
        return "Opening context"
    return f"Section {section_index}"


class SectionSummaryPayload(BaseModel):
    """Structured JSON payload generated by an LLM for one session section."""

    title: str
    summary: str
    goal: str | None = None
    actions: list[str] = Field(default_factory=list)
    outcome: str | None = None
    tool_patterns: list[str] = Field(default_factory=list)
    risk_or_blocker: str | None = None
    keywords: list[str] = Field(default_factory=list)


class SessionSectionSynopsis(BaseModel):
    """Provider-agnostic section input derived from normalized session messages."""

    section_id: str
    session_id: str
    section_index: int
    ecosystem: str
    project_path: str
    title: str
    start_timestamp: str | None = None
    end_timestamp: str | None = None
    total_messages: int
    user_message_count: int
    assistant_message_count: int
    tool_call_count: int
    input_tokens: int
    output_tokens: int
    total_tokens: int
    char_count: int
    duration_seconds: float | None = None
    first_user_message: str | None = None
    last_assistant_message: str | None = None
    notable_tools: list[str] = Field(default_factory=list)
    transcript_excerpt: list[str] = Field(default_factory=list)

    def to_prompt_context(self) -> str:
        lines = [
            f"section_id: {self.section_id}",
            f"session_id: {self.session_id}",
            f"section_index: {self.section_index}",
            f"ecosystem: {self.ecosystem}",
            f"project_path: {self.project_path}",
            f"title: {self.title}",
            f"start_timestamp: {self.start_timestamp or '(unknown)'}",
            f"end_timestamp: {self.end_timestamp or '(unknown)'}",
            f"total_messages: {self.total_messages}",
            f"user_message_count: {self.user_message_count}",
            f"assistant_message_count: {self.assistant_message_count}",
            f"tool_call_count: {self.tool_call_count}",
            f"input_tokens: {self.input_tokens}",
            f"output_tokens: {self.output_tokens}",
            f"total_tokens: {self.total_tokens}",
            f"char_count: {self.char_count}",
            f"duration_seconds: {self.duration_seconds or 0.0}",
            f"first_user_message: {self.first_user_message or '(unknown)'}",
            f"last_assistant_message: {self.last_assistant_message or '(unknown)'}",
            "notable_tools: " + (", ".join(self.notable_tools) if self.notable_tools else "(none)"),
            "transcript_excerpt:",
            *[f"- {line}" for line in self.transcript_excerpt],
        ]
        return "\n".join(lines)


@dataclass(frozen=True)
class SessionSection:
    """Locally derived section boundary and statistics for one session segment."""

    section_id: str
    session_id: str
    section_index: int
    title: str
    start_message_uuid: str
    end_message_uuid: str
    start_timestamp: str | None
    end_timestamp: str | None
    total_messages: int
    user_message_count: int
    assistant_message_count: int
    tool_call_count: int
    input_tokens: int
    output_tokens: int
    total_tokens: int
    char_count: int
    duration_seconds: float | None
    synopsis: SessionSectionSynopsis

    def to_row(self) -> dict[str, object]:
        return {
            "section_id": self.section_id,
            "section_index": self.section_index,
            "title": self.title,
            "start_message_uuid": self.start_message_uuid,
            "end_message_uuid": self.end_message_uuid,
            "start_timestamp": self.start_timestamp,
            "end_timestamp": self.end_timestamp,
            "total_messages": self.total_messages,
            "user_message_count": self.user_message_count,
            "assistant_message_count": self.assistant_message_count,
            "tool_call_count": self.tool_call_count,
            "input_tokens": self.input_tokens,
            "output_tokens": self.output_tokens,
            "total_tokens": self.total_tokens,
            "char_count": self.char_count,
            "duration_seconds": self.duration_seconds,
        }


@dataclass(frozen=True)
class SectionSummaryGeneration:
    """One generated or failed structured section summary."""

    section_id: str
    session_id: str
    section_hash: str
    prompt_version: str
    model_id: str
    status: _SECTION_STATUS
    summary_text: str | None
    summary_json: str | None
    summary_chars: int | None
    generated_at: str
    error_message: str | None = None


@dataclass(frozen=True)
class SectionSummaryStageResult:
    """Aggregate section-summary generation outcome for one run."""

    generated: int = 0
    skipped: int = 0
    failed: int = 0
    sections: int = 0


class SessionSectionSummaryRunner(Protocol):
    """Interface for repository-owned structured section summary backends."""

    def generate(
        self, synopsis: SessionSectionSynopsis, *, config: SummaryGenerationConfig
    ) -> SectionSummaryGeneration:
        """Generate one structured section summary."""


def compute_section_hash(synopsis: SessionSectionSynopsis) -> str:
    """Compute a stable hash over one section synopsis payload."""
    payload = json.dumps(synopsis.model_dump(mode="json"), ensure_ascii=False, sort_keys=True)
    return hashlib.sha256(payload.encode("utf-8")).hexdigest()


def _extract_json_object(raw_text: str) -> dict[str, Any]:
    normalized = raw_text.strip()
    if not normalized:
        raise SessionSummaryGenerationError("section summary runner returned empty output")
    first = normalized.find("{")
    last = normalized.rfind("}")
    if first == -1 or last == -1 or last <= first:
        raise SessionSummaryGenerationError("section summary runner did not return a JSON object")
    try:
        return cast(dict[str, Any], json.loads(normalized[first : last + 1]))
    except json.JSONDecodeError as exc:
        raise SessionSummaryGenerationError(f"invalid section summary JSON: {exc}") from exc


def _normalize_payload(
    payload: SectionSummaryPayload,
    *,
    fallback_title: str,
    max_chars: int,
) -> SectionSummaryPayload:
    return SectionSummaryPayload(
        title=_truncate_text(payload.title or fallback_title, 72) or fallback_title,
        summary=_truncate_text(payload.summary or fallback_title, max_chars),
        goal=_normalize_whitespace(payload.goal) if payload.goal else None,
        actions=[_truncate_text(value, 120) for value in _clip_list(payload.actions, limit=5)],
        outcome=_normalize_whitespace(payload.outcome) if payload.outcome else None,
        tool_patterns=[
            _truncate_text(value, 80) for value in _clip_list(payload.tool_patterns, limit=5)
        ],
        risk_or_blocker=(
            _normalize_whitespace(payload.risk_or_blocker) if payload.risk_or_blocker else None
        ),
        keywords=[_truncate_text(value, 40) for value in _clip_list(payload.keywords, limit=8)],
    )


def derive_session_sections(session: Session, *, ecosystem: str) -> list[SessionSection]:
    """Split one session into ordered sections using user messages as boundaries."""
    messages = session.main_messages
    if not messages:
        return []

    groups: list[tuple[int, list[MessageRecord]]] = []
    prelude: list[MessageRecord] = []
    current: list[MessageRecord] = []
    next_index = 1
    seen_any_user = False
    for message in messages:
        if not seen_any_user and not message.is_user_message:
            prelude.append(message)
            continue
        if message.is_user_message:
            if not seen_any_user and prelude:
                groups.append((0, prelude))
                prelude = []
            elif current:
                groups.append((next_index, current))
                next_index += 1
                current = []
            seen_any_user = True
        current.append(message)

    if current:
        groups.append((next_index if seen_any_user else 0, current))
    elif prelude:
        groups.append((0, prelude))

    sections: list[SessionSection] = []
    for section_index, group in groups:
        first = group[0]
        last = group[-1]
        input_tokens = 0
        output_tokens = 0
        tool_call_count = 0
        char_count = 0
        user_message_count = 0
        assistant_message_count = 0
        tool_names: list[str] = []
        excerpt_lines: list[str] = []
        first_user_message = None
        last_assistant_message = None

        for message in group:
            message_input, message_output = _message_usage(message)
            input_tokens += message_input
            output_tokens += message_output
            tool_call_count += _message_tool_call_count(message)
            char_count += _message_char_count(message)
            if message.is_user_message:
                user_message_count += 1
                if first_user_message is None:
                    first_user_message = _truncate_text(
                        " ".join(_extract_text_fragments(message)),
                        180,
                    )
            if message.is_assistant_message:
                assistant_message_count += 1
                last_assistant_message = _truncate_text(
                    " ".join(_extract_text_fragments(message)),
                    180,
                )
            if message.message is not None and isinstance(message.message.content, list):
                for block in message.message.content:
                    if isinstance(block, dict) and block.get("type") == "tool_use":
                        tool_name = block.get("name")
                        if isinstance(tool_name, str):
                            tool_names.append(tool_name)
            text_preview = _truncate_text(" ".join(_extract_text_fragments(message)), 160)
            if text_preview:
                if message.is_user_message:
                    role = "user"
                elif message.is_assistant_message:
                    role = "assistant"
                else:
                    role = "other"
                excerpt_lines.append(f"{role}: {text_preview}")

        total_tokens = input_tokens + output_tokens
        duration_seconds = None
        if first.parsed_timestamp and last.parsed_timestamp:
            duration_seconds = max(
                (last.parsed_timestamp - first.parsed_timestamp).total_seconds(),
                0.0,
            )

        section_id = f"{session.metadata.session_id}:section:{section_index}"
        title = _default_section_title(group, section_index)
        synopsis = SessionSectionSynopsis(
            section_id=section_id,
            session_id=session.metadata.session_id,
            section_index=section_index,
            ecosystem=ecosystem,
            project_path=session.metadata.project_path,
            title=title,
            start_timestamp=first.timestamp,
            end_timestamp=last.timestamp,
            total_messages=len(group),
            user_message_count=user_message_count,
            assistant_message_count=assistant_message_count,
            tool_call_count=tool_call_count,
            input_tokens=input_tokens,
            output_tokens=output_tokens,
            total_tokens=total_tokens,
            char_count=char_count,
            duration_seconds=duration_seconds,
            first_user_message=first_user_message,
            last_assistant_message=last_assistant_message,
            notable_tools=_clip_list(tool_names, limit=5),
            transcript_excerpt=excerpt_lines[:8],
        )
        sections.append(
            SessionSection(
                section_id=section_id,
                session_id=session.metadata.session_id,
                section_index=section_index,
                title=title,
                start_message_uuid=first.uuid,
                end_message_uuid=last.uuid,
                start_timestamp=first.timestamp,
                end_timestamp=last.timestamp,
                total_messages=len(group),
                user_message_count=user_message_count,
                assistant_message_count=assistant_message_count,
                tool_call_count=tool_call_count,
                input_tokens=input_tokens,
                output_tokens=output_tokens,
                total_tokens=total_tokens,
                char_count=char_count,
                duration_seconds=duration_seconds,
                synopsis=synopsis,
            )
        )
    return sections


class CodexSessionSectionSummaryRunner:
    """Invoke Codex headlessly to generate structured section summaries."""

    def __init__(self, *, repo_root: Path | None = None) -> None:
        self._repo_root = repo_root or Path(__file__).resolve().parent.parent

    def build_command(self, *, config: SummaryGenerationConfig, output_path: Path) -> list[str]:
        command = [
            config.codex_bin,
            "exec",
            "--ephemeral",
            "--skip-git-repo-check",
            "--dangerously-bypass-approvals-and-sandbox",
            "-C",
            str(self._repo_root),
            "--output-last-message",
            str(output_path),
            "-",
        ]
        if config.model:
            command[2:2] = ["--model", config.model]
        return command

    def generate(
        self, synopsis: SessionSectionSynopsis, *, config: SummaryGenerationConfig
    ) -> SectionSummaryGeneration:
        if shutil.which(config.codex_bin) is None:
            raise SessionSummaryGenerationError(
                f"{config.codex_bin} CLI not found in PATH; cannot generate section summaries."
            )

        prompt = build_session_section_summary_prompt(
            synopsis.to_prompt_context(),
            max_chars=config.max_chars,
        )
        section_hash = compute_section_hash(synopsis)
        with tempfile.TemporaryDirectory(prefix="agent-vis-section-") as tmp_dir:
            output_path = Path(tmp_dir) / "section-summary.json"
            command = self.build_command(config=config, output_path=output_path)
            try:
                result = subprocess.run(
                    command,
                    input=prompt,
                    text=True,
                    capture_output=True,
                    check=True,
                    timeout=config.timeout_seconds,
                )
            except subprocess.CalledProcessError as exc:
                stderr = _normalize_whitespace(exc.stderr or "")
                raise SessionSummaryGenerationError(
                    f"codex exec failed with exit code {exc.returncode}: {stderr or 'no stderr'}"
                ) from exc
            except subprocess.TimeoutExpired as exc:
                raise SessionSummaryGenerationError(
                    f"codex exec timed out after {config.timeout_seconds} seconds"
                ) from exc

            raw_text = output_path.read_text(encoding="utf-8") if output_path.exists() else ""
            if not raw_text.strip():
                raw_text = result.stdout
            payload_dict = _extract_json_object(raw_text)
            try:
                payload = SectionSummaryPayload.model_validate(payload_dict)
            except ValidationError as exc:
                raise SessionSummaryGenerationError(
                    f"section summary JSON did not match schema: {exc}"
                ) from exc

        normalized = _normalize_payload(
            payload,
            fallback_title=synopsis.title,
            max_chars=config.max_chars,
        )
        generated_at = datetime.now(timezone.utc).isoformat()
        return SectionSummaryGeneration(
            section_id=synopsis.section_id,
            session_id=synopsis.session_id,
            section_hash=section_hash,
            prompt_version=SESSION_SECTION_SUMMARY_PROMPT_VERSION,
            model_id=config.model_id,
            status="completed",
            summary_text=normalized.summary,
            summary_json=normalized.model_dump_json(),
            summary_chars=len(normalized.summary),
            generated_at=generated_at,
            error_message=None,
        )


class ClaudeSessionSectionSummaryRunner:
    """Invoke Claude Code headlessly to generate structured section summaries."""

    def generate(
        self, synopsis: SessionSectionSynopsis, *, config: SummaryGenerationConfig
    ) -> SectionSummaryGeneration:
        if shutil.which(config.claude_bin) is None:
            raise SessionSummaryGenerationError(
                f"{config.claude_bin} CLI not found in PATH; cannot generate section summaries."
            )

        prompt = build_session_section_summary_prompt(
            synopsis.to_prompt_context(),
            max_chars=config.max_chars,
        )
        section_hash = compute_section_hash(synopsis)
        command = [
            config.claude_bin,
            "-p",
            prompt,
            "--dangerously-skip-permissions",
            "--no-session-persistence",
        ]
        if config.model:
            command.extend(["--model", config.model])

        env = None
        if "CLAUDE_CODE_ENTRYPOINT" in os.environ:
            env = os.environ.copy()
            env.pop("CLAUDE_CODE_ENTRYPOINT", None)

        try:
            result = subprocess.run(
                command,
                capture_output=True,
                text=True,
                check=True,
                timeout=config.timeout_seconds,
                env=env,
            )
        except subprocess.CalledProcessError as exc:
            stderr = _normalize_whitespace(exc.stderr or "")
            raise SessionSummaryGenerationError(
                f"claude -p failed with exit code {exc.returncode}: {stderr or 'no stderr'}"
            ) from exc
        except subprocess.TimeoutExpired as exc:
            raise SessionSummaryGenerationError(
                f"claude -p timed out after {config.timeout_seconds} seconds"
            ) from exc

        payload_dict = _extract_json_object(result.stdout)
        try:
            payload = SectionSummaryPayload.model_validate(payload_dict)
        except ValidationError as exc:
            raise SessionSummaryGenerationError(
                f"section summary JSON did not match schema: {exc}"
            ) from exc

        normalized = _normalize_payload(
            payload,
            fallback_title=synopsis.title,
            max_chars=config.max_chars,
        )
        generated_at = datetime.now(timezone.utc).isoformat()
        return SectionSummaryGeneration(
            section_id=synopsis.section_id,
            session_id=synopsis.session_id,
            section_hash=section_hash,
            prompt_version=SESSION_SECTION_SUMMARY_PROMPT_VERSION,
            model_id=config.model_id,
            status="completed",
            summary_text=normalized.summary,
            summary_json=normalized.model_dump_json(),
            summary_chars=len(normalized.summary),
            generated_at=generated_at,
            error_message=None,
        )


def build_section_summary_runner(config: SummaryGenerationConfig) -> SessionSectionSummaryRunner:
    """Select the configured section-summary backend."""
    if config.backend == "claude":
        return ClaudeSessionSectionSummaryRunner()
    return CodexSessionSectionSummaryRunner()


@dataclass(frozen=True)
class _SectionWorkItem:
    section: SessionSection
    section_hash: str


class SessionSectionSummaryCoordinator:
    """Fan out structured section summary generation for persisted sessions."""

    def __init__(
        self,
        repo: SessionRepository,
        runner: SessionSectionSummaryRunner,
        config: SummaryGenerationConfig,
    ) -> None:
        self._repo = repo
        self._runner = runner
        self._config = config
        self._write_lock = Lock()

    def _should_skip(self, section_id: str, section_hash: str) -> bool:
        existing = self._repo.get_session_section_summary(section_id)
        if existing is None:
            return False
        return (
            existing["section_hash"] == section_hash
            and existing["prompt_version"] == SESSION_SECTION_SUMMARY_PROMPT_VERSION
            and existing["model_id"] == self._config.model_id
            and existing["generation_status"] == "completed"
            and bool(existing["summary_json"])
        )

    def _persist_generation(self, generation: SectionSummaryGeneration) -> None:
        with self._write_lock:
            self._repo.upsert_session_section_summary(
                section_id=generation.section_id,
                session_id=generation.session_id,
                section_hash=generation.section_hash,
                prompt_version=generation.prompt_version,
                model_id=generation.model_id,
                generation_status=generation.status,
                summary_text=generation.summary_text,
                summary_json=generation.summary_json,
                summary_chars=generation.summary_chars,
                generated_at=generation.generated_at,
                error_message=generation.error_message,
            )

    def generate_for_sessions(
        self,
        sessions: list[Session],
        *,
        ecosystem: str,
    ) -> SectionSummaryStageResult:
        if not self._config.enabled:
            return SectionSummaryStageResult()

        work_items: list[_SectionWorkItem] = []
        skipped = 0
        total_sections = 0
        for session in sessions:
            sections = derive_session_sections(session, ecosystem=ecosystem)
            total_sections += len(sections)
            self._repo.replace_session_sections(
                session.metadata.session_id,
                [section.to_row() for section in sections],
            )
            for section in sections:
                section_hash = compute_section_hash(section.synopsis)
                if self._should_skip(section.section_id, section_hash):
                    skipped += 1
                    continue
                work_items.append(_SectionWorkItem(section=section, section_hash=section_hash))

        if not work_items:
            return SectionSummaryStageResult(
                generated=0,
                skipped=skipped,
                failed=0,
                sections=total_sections,
            )

        generated = 0
        failed = 0
        max_workers = max(1, min(self._config.max_workers, len(work_items)))
        with ThreadPoolExecutor(max_workers=max_workers) as executor:
            futures = {
                executor.submit(
                    self._runner.generate,
                    item.section.synopsis,
                    config=self._config,
                ): item
                for item in work_items
            }
            for future in as_completed(futures):
                item = futures[future]
                try:
                    generation = future.result()
                except Exception as exc:
                    generation = SectionSummaryGeneration(
                        section_id=item.section.section_id,
                        session_id=item.section.session_id,
                        section_hash=item.section_hash,
                        prompt_version=SESSION_SECTION_SUMMARY_PROMPT_VERSION,
                        model_id=self._config.model_id,
                        status="failed",
                        summary_text=None,
                        summary_json=None,
                        summary_chars=None,
                        generated_at=datetime.now(timezone.utc).isoformat(),
                        error_message=str(exc),
                    )
                    failed += 1
                else:
                    generated += 1
                self._persist_generation(generation)

        return SectionSummaryStageResult(
            generated=generated,
            skipped=skipped,
            failed=failed,
            sections=total_sections,
        )
